@pass_context
def org_setting_fn(ctx, key, default=""):
    request = ctx.get("request")
    if request is None:
        return default
    if not hasattr(request.state, "_org_cache"):
        from .database import SessionLocal
        from .models import Setting
        db = SessionLocal()
        try:
            rows = db.query(Setting).filter(Setting.key.like("org_%")).all()
            request.state._org_cache = {r.key: r.value for r in rows}
        finally:
            db.close()
    return request.state._org_cache.get(key) or default
